-- 001: tablas normalizadas (3FN) con llaves, reglas de calidad e índices - Oracle 23ai

-- ---------- Catálogos ----------

CREATE TABLE categorias (
  id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nombre     VARCHAR2(50) NOT NULL,
  creado_en  DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT ck_categorias_nombre CHECK (TRIM(nombre) IS NOT NULL)
);
CREATE UNIQUE INDEX uq_categorias_nombre ON categorias (UPPER(nombre));

CREATE TABLE productos (
  id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nombre        VARCHAR2(100) NOT NULL,
  precio        NUMBER(10,2) NOT NULL,
  stock         NUMBER(10) DEFAULT 0 NOT NULL,
  categoria_id  NUMBER NOT NULL,
  creado_en     DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT fk_productos_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id),
  CONSTRAINT ck_productos_nombre CHECK (TRIM(nombre) IS NOT NULL),
  CONSTRAINT ck_productos_precio CHECK (precio >= 0),
  CONSTRAINT ck_productos_stock  CHECK (stock >= 0)
);
CREATE INDEX idx_productos_categoria ON productos (categoria_id);

CREATE TABLE clientes (
  id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nombre     VARCHAR2(100) NOT NULL,
  nit_dpi    VARCHAR2(20) NOT NULL,
  correo     VARCHAR2(100),
  creado_en  DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT uq_clientes_nit_dpi UNIQUE (nit_dpi),
  CONSTRAINT ck_clientes_nombre  CHECK (TRIM(nombre) IS NOT NULL),
  CONSTRAINT ck_clientes_nit_dpi CHECK (REGEXP_LIKE(nit_dpi, '^[0-9Kk-]+$')),
  CONSTRAINT ck_clientes_correo  CHECK (correo IS NULL OR REGEXP_LIKE(correo, '^[^@[:space:]]+@[^@[:space:]]+[.][^@[:space:]]+$'))
);
CREATE UNIQUE INDEX uq_clientes_correo ON clientes (UPPER(correo));

CREATE TABLE proveedores (
  id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nombre     VARCHAR2(100) NOT NULL,
  nit        VARCHAR2(20) NOT NULL,
  telefono   VARCHAR2(20),
  creado_en  DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT uq_proveedores_nit UNIQUE (nit),
  CONSTRAINT ck_proveedores_nombre CHECK (TRIM(nombre) IS NOT NULL),
  CONSTRAINT ck_proveedores_nit CHECK (REGEXP_LIKE(nit, '^[0-9Kk-]+$'))
);

CREATE TABLE tipos_gasto (
  id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nombre  VARCHAR2(50) NOT NULL,
  CONSTRAINT ck_tipos_gasto_nombre CHECK (TRIM(nombre) IS NOT NULL)
);
CREATE UNIQUE INDEX uq_tipos_gasto_nombre ON tipos_gasto (UPPER(nombre));

-- ---------- Ingresos: ventas ----------

CREATE TABLE ventas (
  id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  cliente_id  NUMBER NOT NULL,
  fecha       DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT fk_ventas_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (id)
);
CREATE INDEX idx_ventas_cliente ON ventas (cliente_id);
CREATE INDEX idx_ventas_fecha ON ventas (fecha);

CREATE TABLE detalle_venta (
  venta_id         NUMBER NOT NULL,
  producto_id      NUMBER NOT NULL,
  cantidad         NUMBER(10) NOT NULL,
  precio_unitario  NUMBER(10,2) NOT NULL,
  CONSTRAINT pk_detalle_venta PRIMARY KEY (venta_id, producto_id),
  CONSTRAINT fk_detalle_venta_venta    FOREIGN KEY (venta_id) REFERENCES ventas (id) ON DELETE CASCADE,
  CONSTRAINT fk_detalle_venta_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
  CONSTRAINT ck_detalle_venta_cantidad CHECK (cantidad > 0),
  CONSTRAINT ck_detalle_venta_precio   CHECK (precio_unitario >= 0)
);
CREATE INDEX idx_detalle_venta_producto ON detalle_venta (producto_id);

-- ---------- Egresos: compras y gastos ----------

CREATE TABLE compras (
  id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  proveedor_id  NUMBER NOT NULL,
  fecha         DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT fk_compras_proveedor FOREIGN KEY (proveedor_id) REFERENCES proveedores (id)
);
CREATE INDEX idx_compras_proveedor ON compras (proveedor_id);
CREATE INDEX idx_compras_fecha ON compras (fecha);

CREATE TABLE detalle_compra (
  compra_id       NUMBER NOT NULL,
  producto_id     NUMBER NOT NULL,
  cantidad        NUMBER(10) NOT NULL,
  costo_unitario  NUMBER(10,2) NOT NULL,
  CONSTRAINT pk_detalle_compra PRIMARY KEY (compra_id, producto_id),
  CONSTRAINT fk_detalle_compra_compra   FOREIGN KEY (compra_id) REFERENCES compras (id) ON DELETE CASCADE,
  CONSTRAINT fk_detalle_compra_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
  CONSTRAINT ck_detalle_compra_cantidad CHECK (cantidad > 0),
  CONSTRAINT ck_detalle_compra_costo    CHECK (costo_unitario >= 0)
);
CREATE INDEX idx_detalle_compra_producto ON detalle_compra (producto_id);

CREATE TABLE gastos (
  id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  tipo_gasto_id  NUMBER NOT NULL,
  descripcion    VARCHAR2(200) NOT NULL,
  monto          NUMBER(10,2) NOT NULL,
  fecha          DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
  creado_en      DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT fk_gastos_tipo FOREIGN KEY (tipo_gasto_id) REFERENCES tipos_gasto (id),
  CONSTRAINT ck_gastos_descripcion CHECK (TRIM(descripcion) IS NOT NULL),
  CONSTRAINT ck_gastos_monto CHECK (monto > 0)
);
CREATE INDEX idx_gastos_tipo ON gastos (tipo_gasto_id);
CREATE INDEX idx_gastos_fecha ON gastos (fecha);

-- ---------- Documentación visible en SQL Developer ----------

COMMENT ON TABLE categorias     IS 'Clasificación de los productos';
COMMENT ON TABLE productos      IS 'Catálogo de productos con precio y existencias';
COMMENT ON TABLE clientes       IS 'Clientes con sus datos de facturación';
COMMENT ON TABLE proveedores    IS 'Proveedores a los que se compra mercadería';
COMMENT ON TABLE tipos_gasto    IS 'Clasificación de los gastos de operación';
COMMENT ON TABLE ventas         IS 'Encabezado de cada venta: cliente y fecha (ingreso)';
COMMENT ON TABLE detalle_venta  IS 'Productos de cada venta (resuelve la relación N:M entre ventas y productos)';
COMMENT ON TABLE compras        IS 'Encabezado de cada compra: proveedor y fecha (egreso)';
COMMENT ON TABLE detalle_compra IS 'Productos de cada compra; al registrarla aumenta el stock';
COMMENT ON TABLE gastos         IS 'Gastos de operación: alquiler, servicios, sueldos, etc. (egreso)';
COMMENT ON COLUMN productos.stock                IS 'Unidades disponibles; baja al vender y sube al comprar';
COMMENT ON COLUMN clientes.nit_dpi               IS 'NIT o DPI del cliente, único';
COMMENT ON COLUMN ventas.fecha                   IS 'Fecha y hora de la venta (hora de Guatemala)';
COMMENT ON COLUMN detalle_venta.precio_unitario  IS 'Precio al momento de la venta (no cambia si después cambia el precio)';
COMMENT ON COLUMN detalle_compra.costo_unitario  IS 'Costo pagado al proveedor por unidad';
